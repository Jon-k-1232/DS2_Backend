'use strict';
const PDFDocument=require('pdfkit');
const {createHash}=require('crypto');
const p=require('./audit-record-presentation');
const sha256=b=>createHash('sha256').update(b).digest('hex');
const ZERO='0'.repeat(64);

// Same fixed-width digest protocol as run 4. Presentation never changes capture.
async function render(data, meta) {
   const type=meta.record_type || 'client',full=type==='full_evidence';
   const entries=data.entries.every(e=>e.presentation)?data.entries:p.present(data.entries,data.reference_data);
   const counts=p.coverage(entries);
   const doc=new PDFDocument({size:'LETTER',margin:42,compress:false,bufferPages:true,
      info:{Title:p.TYPES[type]+' - Account history and audit record',Author:meta.generated_by_name,CreationDate:new Date(meta.generated_at)}});
   const parts=[];
   const done=new Promise((resolve,reject)=>{doc.on('data',b=>parts.push(b));doc.on('end',()=>resolve(Buffer.concat(parts)));doc.on('error',reject);});
   const line=(text,opts={})=>doc.text(text,42,doc.y,{width:528,lineGap:1,...opts});
   const room=h=>{if(doc.y+h>730)doc.addPage();};
   const section=text=>{room(45);doc.moveDown(.6).font('Helvetica-Bold').fontSize(12);line(text);doc.moveDown(.35).font('Helvetica').fontSize(8.5);};
   doc.font('Helvetica-Bold').fontSize(18);line(p.TYPES[type]);
   doc.fontSize(11);line('Account history and audit record');
   doc.moveDown(.35).fontSize(10);line(meta.firm+' | '+data.customer.display_name);
   doc.font('Helvetica').fontSize(9);
   line(`Range: ${data.startDate || 'Beginning of records'} through ${data.endDate || 'Generation time'}`);
   line(`Generated by ${meta.generated_by_name} at ${p.time(meta.generated_at)} (America/Phoenix)`);
   line('Drafts remain editable; finalize means sent and locked.');
   doc.moveDown(.4).fontSize(8.5);line(data.methodology);
   line(`Audit logging began: ${p.time(data.logging_started_at)}. Earlier entries are reconstructed from existing records, before audit logging began.`);
   section('Ledger');
   line(`Opening balance: ${p.money(data.opening_balance)}. Debit / Credit are positive amounts; credit balances use -$1,234.56. Retainer is available funds, separate from debt.`);
   doc.moveDown(.4);
   const columns=[{x:308,width:62,key:'debit',title:'Debit'},{x:376,width:62,key:'credit',title:'Credit'},
      {x:444,width:62,key:'balance',title:'Balance'},{x:512,width:58,key:'retainer',title:'Retainer'}];
   const ledgerHeader=()=>{
      const y=doc.y;doc.font('Helvetica-Bold').fontSize(8);
      doc.text('Posting / business activity / posted by',42,y,{width:260});
      for(const col of columns)doc.text(col.title,col.x,y,{width:col.width,align:'right'});
      doc.y=y+16;doc.font('Helvetica');
   };
   ledgerHeader();
   for(const entry of entries) {
      const view=entry.presentation;
      const text=`${view.number}. ${p.time(entry.occurred_at)}${entry.reconstructed?' (reconstructed)':''}\n${view.description}\nPosted by ${view.actors.join(', ')}`;
      doc.fontSize(8);
      let remaining=text,first=true;
      const wholeHeight=doc.heightOfString(text,{width:260,lineGap:1})+9;
      if(doc.y+wholeHeight>730 && doc.y>70){doc.addPage();ledgerHeader();}
      while(remaining) {
         if(doc.y>685){doc.addPage();ledgerHeader();}
         const y=doc.y,space=730-y-9;
         let length=remaining.length;
         if(doc.heightOfString(remaining,{width:260,lineGap:1})>space) {
            let low=1,high=length;
            while(low<high){const mid=Math.ceil((low+high)/2);if(doc.heightOfString(remaining.slice(0,mid),{width:260,lineGap:1})<=space)low=mid;else high=mid-1;}
            length=low;
            const boundary=remaining.lastIndexOf(' ',length);if(boundary>length/2)length=boundary;
         }
         const chunk=remaining.slice(0,length),height=doc.heightOfString(chunk,{width:260,lineGap:1})+9;
         doc.text(chunk,42,y,{width:260,lineGap:1});
         if(first)for(const col of columns)doc.text(view[col.key],col.x,y,{width:col.width,align:'right'});
         doc.y=y+height;remaining=remaining.slice(length).trimStart();first=false;
         if(remaining){doc.addPage();ledgerHeader();}
      }
   }
   line(`Closing balance: ${p.money(data.closing_balance)}`);
   section('Change log');
   line(`${counts.postings} postings; ${counts.changes} record changes (${counts.captured_changes} captured, ${counts.reconstructed_changes} reconstructed). ${counts.fields} field changes: ${full?counts.human_fields:counts.client_human_fields} business values shown; ${full?counts.supporting_fields:counts.client_supporting_fields} supporting fields retained in evidence.`);
   line(full?'Structured values are described below; retrieve their exact contents using the verified evidence API and JSON Pointer shown.':`${counts.changes-counts.summarized_changes} changes listed individually; ${counts.summarized_changes} archived statement-copy changes covered by ${counts.archive_summaries} summary lines. Each summary states the changes it covers. Administrative identifiers and structured evidence are retained in the full evidence record and verified archive.`);
   const evidencePath=meta.evidence_path || '(legacy record: no separate evidence archive)';
   if(full) {line('Verified evidence API: GET '+evidencePath);line('Payload bytes and hashes use UTF-8 JSON.stringify(value), with key order as archived.');}
   let entryIndex=0;
   for(const entry of entries) {
      const view=entry.presentation;
      room(48);doc.moveDown(.6).font('Helvetica-Bold').fontSize(9);
      line(`Posting ${view.number} | ${p.time(entry.occurred_at)}${entry.reconstructed?' | Reconstructed':''} | ${view.actors.join(', ')}`);
      doc.font('Helvetica').fontSize(8.5);
      if(full)line(`Transaction: ${entry.transaction_id || 'Pre-logging'} | Request: ${entry.correlation_id || 'Not recorded'}`);
      const reasons=[...new Set((full?entry.events.map(e=>e.reason):view.changes.map(c=>c.reason)).filter(Boolean))];
      if(reasons.length===1)line('Reason: '+reasons[0]);
      const printedChanges=full?view.changes:(view.client_changes || view.changes);
      for(let i=0;i<printedChanges.length;i++) {
         const e=entry.events[i],change=printedChanges[i];
         if(!full && change.kind==='statement_archive') {
            room(48);doc.font('Helvetica').fontSize(8.5);
            line(change.text+(view.actors.length>1?' | '+change.actor:''));
            if(reasons.length>1 && change.reason)line('Reason: '+change.reason);
            continue;
         }
         room(24);doc.font('Helvetica-Bold').fontSize(8.5);
         line(`Change ${change.number}. ${change.operation}: ${change.label}${view.actors.length>1?' | '+change.actor:''}${!full && !change.fields.length && change.summaries.length?' - '+change.summaries.join(' '):''}`);
         doc.font('Helvetica');
         if(full) {
            line(`Evidence event ${e.event_id}; record ${e.entity_id}; action ${e.action}; actor ${e.actor_name}${e.actor_user_id?' (user #'+e.actor_user_id+')':''}; source ${e.source || 'Not recorded'}`);
            const effects=[];
            if(e.debit || e.credit)effects.push(`Debit ${p.money(e.debit)}; Credit ${p.money(e.credit)}`);
            if(e.retainer_delta)effects.push(`Retainer availability change ${p.money(e.retainer_delta)}`);
            if(e.invoice_total!==undefined)effects.push(`Invoice total ${p.money(e.invoice_total)} (statement marker, not another charge)`);
            if(effects.length)line(effects.join('; '));
            const changes=p.changesOf(e);
            const value=(key,v,side)=>{
               if(v===null || v===undefined)return 'Not set';
               if(typeof v==='object' || String(v).length>180) {
                  const d=p.descriptor(v);
                  const pointer=`/data/entries/${entryIndex}/events/${i}/${e.reconstructed?'after_value/'+key:'changes/'+key+'/'+side}`;
                  return `${d.type}, ${d.byte_length} bytes, SHA-256 ${d.sha256};\nRetrieve ${pointer}`;
               }
               return p.formatted(key,v);
            };
            let shortFields=[];
            const flush=()=>{if(shortFields.length){line(shortFields.join('; '));shortFields=[];}};
            for(const [key,v] of Object.entries(changes)) {
               // New/deleted rows list their meaningful side once; full null and
               // unchanged before-images remain available in the source archive.
               const text=`${p.human(key)}: ${e.action==='insert' || e.reconstructed?value(key,v.after,'after'):e.action==='delete'?value(key,v.before,'before'):value(key,v.before,'before')+' -> '+value(key,v.after,'after')}`;
               if(text.length>210){flush();line(text);}else shortFields.push(text);
            }
            flush();
         } else {
            if(change.fields.length)line(change.fields.map(f=>f.text).join('; '));
            if(change.fields.length)for(const summary of change.summaries)line(summary);
         }
         const reason=full?e.reason:change.reason;
         if(reasons.length>1 && reason)line('Reason: '+reason);
      }
      entryIndex++;
   }
   section('Closing position');
   line(`Closing balance for this range: ${p.money(data.closing_balance)}`);
   line(`Current balance at generation: ${p.money(data.current.running_balance)} (billed ${p.money(data.current.billed_balance)}; unbilled ${p.money(data.current.unbilled_balance)}). Retainer available: ${p.money(data.current.retainer_available)}.`);
   room(180);section('Verification');
   line(`Record ID: ${meta.record_id} | ${p.TYPES[type]}`);
   line(`Hash-chain anchor event: ${data.verification.event_id || 'genesis'}`);
   doc.font('Courier').fontSize(7.5);line(data.verification.hash);
   doc.font('Helvetica').fontSize(8.5);
   if(meta.evidence_sha256){line('Verified source archive SHA-256:');doc.font('Courier').fontSize(7.5);line(meta.evidence_sha256);doc.font('Helvetica').fontSize(8.5);if(full)line('Retrieve via GET '+evidencePath);}
   line('Document SHA-256 (the digest field below is zeroed for calculation):');
   const digestPrefix=`AUDIT-SHA256/${meta.record_id}:`;
   doc.font('Courier').fontSize(7);line(digestPrefix+ZERO,{lineBreak:false});doc.moveDown();
   doc.font('Helvetica').fontSize(8.5);line(full?'The complete stored-file SHA-256 is listed in Audit Record and its verification endpoint. Reopen by record ID to retrieve these exact bytes.':"To confirm this document is authentic and unchanged, give the firm its record ID; the firm's system recomputes the SHA-256 digest and checks it against the stored original and the audit chain. The firm can reopen the exact stored document using this ID.");
   const range=doc.bufferedPageRange();
   for(let i=0;i<range.count;i++) {
      doc.switchToPage(i);
      // PDFKit otherwise pushes a footer below the body margin onto a NEW page.
      const bottom=doc.page.margins.bottom;doc.page.margins.bottom=20;
      doc.font('Helvetica').fontSize(8).text(`Account history and audit record | ${meta.record_id} | ${i+1} / ${range.count}`,48,752,{width:516,lineBreak:false});
      doc.page.margins.bottom=bottom;
   }
   doc.end();
   const zeroed=await done;
   const placeholder=Buffer.from(digestPrefix+ZERO).toString('hex');
   const markerIndex=zeroed.indexOf(placeholder);
   if(markerIndex<0 || zeroed.indexOf(placeholder,markerIndex+placeholder.length)>=0)throw new Error('PDF digest field is not unique');
   const index=markerIndex+Buffer.byteLength(digestPrefix)*2;
   const contentHash=sha256(zeroed);
   const body=Buffer.from(zeroed);
   body.write(Buffer.from(contentHash).toString('hex'),index,'ascii');
   return {body,document_sha256:sha256(body),content_sha256:contentHash};
}
function verifyContent(body,hash) {
   const encoded=Buffer.from(hash).toString('hex');
   const index=body.indexOf(encoded);
   if(index<0 || body.indexOf(encoded,index+encoded.length)>=0)return false;
   const zeroed=Buffer.from(body);zeroed.write(Buffer.from(ZERO).toString('hex'),index,'ascii');
   return sha256(zeroed)===hash;
}
module.exports={render,sha256,verifyContent};
