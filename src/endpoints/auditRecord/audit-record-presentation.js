function references(entries, referenceData={}) {
 const maps={};
 for(const e of entries.flatMap(x=>x.events)) {
  if(!maps[e.entity])maps[e.entity]=new Map();
  // Labels for deleted records survive, and later edits never replace a label
  // during replay. Initial state comes from earliest captured before-images.
  if(!maps[e.entity].has(String(e.entity_id)))maps[e.entity].set(String(e.entity_id),e.before_value || e.after_value || {});
 }
 const refs={...referenceData.current};
 for(const change of [...(referenceData.changes || [])].reverse())refs[change.key]=change.before;
 return {maps,refs,referenceChanges:referenceData.changes || [],cursor:0};
}
function prepareReference(ctx,e) {
 if(!e.reconstructed)while(ctx.cursor<ctx.referenceChanges.length && BigInt(ctx.referenceChanges[ctx.cursor].event_id)<=BigInt(e.event_id)) {
  const c=ctx.referenceChanges[ctx.cursor++];ctx.refs[c.key]=c.after;
 }
 if(e.after_value){if(!ctx.maps[e.entity])ctx.maps[e.entity]=new Map();ctx.maps[e.entity].set(String(e.entity_id),e.after_value);}
}
