function changeNumbers(numbers) {
 const ranges=[];
 for(let i=0;i<numbers.length;i++) {
  const start=numbers[i];let end=start;
  while(numbers[i+1]===end+1)end=numbers[++i];
  ranges.push(start===end?String(start):`${start}-${end}`);
 }
 return ranges.join(', ');
}
// Keep the itemized changes intact for full evidence. Only the client view
// groups newly archived copies, within one posting and one invoice/revision.
// Reversal additions are a separate posting, never attributed to finalization.
function clientChanges(entry,changes,ctx) {
 const groups=new Map(),rows=[];
 entry.events.forEach((e,i)=>{
  const change=changes[i],r=e.after_value || {},ids={covered_event_ids:[e.event_id],covered_change_numbers:[change.number],change_count:1};
  if(e.entity!=='invoice_statement_members' || (!e.reconstructed && e.action!=='insert') || r.invoice_id==null) {
   rows.push({...change,...ids});return;
  }
  const related=entity=>entry.events.filter(x=>x.entity===entity && String((x.after_value || {}).invoice_id)===String(r.invoice_id));
  const revision=r.revision ?? related('invoice_revisions')[0]?.after_value.revision;
  const key=JSON.stringify([r.account_id,r.invoice_id,revision,!!e.reconstructed]);
  let group=groups.get(key);
  if(!group) {
   const issue=related('invoice_issues')[0]?.after_value || rowFor(ctx,'invoice_issues',r.invoice_id);
   const name=invoiceName({...r,invoice_number:issue.invoice_number},ctx);
   const title=name==='invoice'?'Invoice (number not recorded)':`Invoice ${name}`;
   const action=e.reconstructed?'statement archive (reconstructed)':Number(revision)>0?`revision ${revision} archived (sent and locked)`:
    related('invoice_issues').length?'finalized (sent and locked)':
    related('invoice_history').some(x=>x.after_value.event==='exception_reversed')?'bounced check reversal archived (locked)':'statement archive (locked)';
   group={kind:'statement_archive',event_id:e.event_id,number:change.number,title:`${title} ${action}`,
    covered_event_ids:[],covered_change_numbers:[],change_count:0,item_counts:{},actors:[],reasons:[],reconstructed:!!e.reconstructed};
   groups.set(key,group);rows.push(group);
  }
  group.covered_event_ids.push(e.event_id);group.covered_change_numbers.push(change.number);group.change_count++;
  const kind=statementKinds.some(([key])=>key===r.table_name)?r.table_name:'other';
  group.item_counts[kind]=(group.item_counts[kind] || 0)+1;
  if(!group.actors.includes(change.actor))group.actors.push(change.actor);
  if(change.reason && !group.reasons.includes(change.reason))group.reasons.push(change.reason);
 });
 for(const group of groups.values()) {
  const kinds=[...statementKinds,['other','other statement item','other statement items']];
  const breakdown=kinds.filter(([key])=>group.item_counts[key]).map(([key,one,many])=>`${group.item_counts[key]} ${group.item_counts[key]===1?one:many}`).join(', ');
  group.text=`${group.title}: ${group.change_count} statement ${group.change_count===1?'item':'items'} archived - ${breakdown}. Covers ${group.change_count} ${group.reconstructed?'reconstructed':'captured'} ${group.change_count===1?'change':'changes'} (change ${group.change_count===1?'number':'numbers'} ${changeNumbers(group.covered_change_numbers)}). Itemized in the full evidence record.`;
  group.actor=group.actors.join(', ');group.reason=group.reasons.join('; ');
 }
 return rows;
}
function present(entries,referenceData) {
 const ctx=references(entries,referenceData);let sequence=0;
 return entries.map((entry,i)=>{
  for(const e of entry.events)prepareReference(ctx,e);
  const changes=entry.events.map(e=>detail(e,ctx,++sequence));
  return {...entry,presentation:{number:i+1,description:business(entry,ctx),actors:[...new Set(changes.map(c=>c.actor))],
   debit:money(entry.events.reduce((n,e)=>n+(e.debit || 0),0)),credit:money(entry.events.reduce((n,e)=>n+(e.credit || 0),0)),
   balance:money(entry.running_balance),retainer:money(entry.retainer_available),changes,client_changes:clientChanges(entry,changes,ctx)}};
 });
}
