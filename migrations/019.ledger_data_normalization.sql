-- 019: ledger data normalization (2026-09-22 review; 2026-09-23 revision — fail-closed
-- total_payments flips + row-level audit evidence for every changed field). Idempotent; safe
-- to re-run.
--
-- Apply to dev with `npm run migrate`; apply to PROD BY HAND after review:
--   PGPASSWORD=... psql -h <rds> -U <user> -d ds2_prod -X -1 -v ON_ERROR_STOP=1 -f migrations/019.ledger_data_normalization.sql
-- Take a backup first. The command above COMMITs automatically on success.
-- Inspect counts in a separate BEGIN/file/ROLLBACK rehearsal before the committing run (see
-- migrations/README.md).
--
-- FILE CONTRACT (see migrations/README.md): this file is PLAIN SQL — no BEGIN/COMMIT and no
-- psql meta-commands. `scripts/migrate.js` wraps it in its own transaction; a by-hand run needs
-- `psql -X -1` (single-transaction mode) to get the same wrapping — the LOCK TABLE below only
-- protects the rest of this file when it does. Don't add BEGIN/COMMIT back: that would end
-- whichever wrapper transaction is supposed to own this file's atomicity.
--
-- 1. transaction_type casing. The auto-ingest and manual-submission paths wrote
--    'time' (5,130 prod rows) while the UI writes 'Time'; every analytics and
--    employee-time query compares against 'Time' exactly, so those hours and
--    dollars were invisible to reports. The API now normalises on write.
-- 2. Literal 'null' / 'undefined' strings produced by `String(x) || ''` mappers
--    (33,129 transaction notes in prod).
-- 3. customer_invoices.total_payments sign — FAIL CLOSED (2026-09-23 revision). The June-2026
--    code stores the column as a NEGATIVE net (same sign as customer_payments rows); legacy
--    rows stored a POSITIVE magnitude (918 parents in prod). A flip used to be driven by
--    arithmetic equality alone (stored value == magnitude of payments tagged to the chain, no
--    positive/reversal rows) — but arithmetic equality is not proof of correct attribution: a
--    reversal payment tagged to a DIFFERENT root, or a child invoice whose payments roll up to
--    a root owned by a DIFFERENT customer, can produce the exact same arithmetic match while
--    flipping the wrong row (round-3 review, finding F2 — reproduced against fixtures with
--    both shapes). A row now flips ONLY when it appears in the _m019_reviewed manifest below
--    (account_id, customer_id, root_id, the old total, the signed net, and the exact set of
--    payment ids all pre-declared) AND the live data still matches every one of those expected
--    values exactly AND the chain has no reversal event of its own (s.positive_events = 0) AND
--    no OTHER payment or linked child row anywhere in the chain belongs to a different
--    account/customer (the NOT EXISTS ownership check below — follow-up finding N4: a root's
--    OWN arithmetic group can match exactly while a foreign payment still sits elsewhere in the
--    same chain via a child invoice, which is exactly the misattribution shape this migration
--    exists to stop flipping). The manifest starts EMPTY — "accountant-reviewed rows go here" —
--    so this migration flips NOTHING in prod until a reviewed block is pasted in. Generate the
--    accountant CSV and the matching SQL INSERT block with
--    `node scripts/review-2026-09/positive-total-payments-manifest.js` (read-only; the generator
--    applies the same reversal and ownership quarantine, so nothing it lists can fail these
--    checks unless the live data changed between generation and review). Child snapshots are
--    never touched (they need event-time reconciliation).
-- 4. Row-level audit evidence. Every field this migration changes — not just total_payments —
--    is logged to ledger_normalization_log with its before/after value, idempotently: the
--    before-image capture below only ever selects rows still in the "before" (unfixed) state,
--    so a rerun that finds nothing left to fix logs nothing new.

-- Permanent evidence of every row this migration changed (the accountant's manifest; also what
-- you would use to revert a single row).
CREATE TABLE IF NOT EXISTS ledger_normalization_log (
   log_id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
   migration text NOT NULL,
   table_name text NOT NULL,
   row_id integer NOT NULL,
   account_id integer,
   customer_id integer,
   column_name text NOT NULL,
   old_value text,
   new_value text,
   applied_at timestamptz NOT NULL DEFAULT now()
);

-- Keep the before-images below stable through their UPDATEs and the audit INSERT — nothing else
-- may change these four tables mid-migration. Held for the rest of the wrapper transaction
-- (see FILE CONTRACT above — this is why the file cannot supply its own BEGIN/COMMIT).
LOCK TABLE customer_transactions, customer_payments, customer_writeoffs, customer_invoices
   IN SHARE ROW EXCLUSIVE MODE;

-- Every field-level change this file is about to make, captured BEFORE any UPDATE runs. A
-- rerun only ever finds rows still in the "before" state here — an already-fixed row no longer
-- matches these WHERE clauses — which is what makes the log insert below idempotent for these
-- columns with no separate dedup check needed.
