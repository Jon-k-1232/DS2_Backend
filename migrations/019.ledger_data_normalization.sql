-- ── total_payments sign flip: FAIL CLOSED (F2) ───────────────────────────────────────────────
-- Populated ONLY from an independently reviewed manifest generated by
-- scripts/review-2026-09/positive-total-payments-manifest.js. Empty here means quarantine:
-- nothing below flips until a reviewed block is pasted in.
CREATE TEMP TABLE _m019_reviewed (
   account_id integer NOT NULL,
   customer_id integer NOT NULL,
   root_id integer PRIMARY KEY,
   expected_old_total numeric NOT NULL,
   expected_signed_net numeric NOT NULL,
   expected_payment_ids integer[] NOT NULL
) ON COMMIT DROP;

-- accountant-reviewed rows go here
-- INSERT INTO _m019_reviewed (account_id, customer_id, root_id, expected_old_total, expected_signed_net, expected_payment_ids) VALUES
--    (1, 123, 456, 500.00, -500.00, ARRAY[789, 790]);

WITH resolved AS (
   SELECT p.payment_id, p.account_id, p.customer_id, p.payment_amount,
          COALESCE(i.parent_invoice_id, i.customer_invoice_id) AS root_id
   FROM customer_payments p
   JOIN customer_invoices i ON i.customer_invoice_id = p.customer_invoice_id
   WHERE i.account_id = p.account_id AND i.customer_id = p.customer_id
), sums AS (
   SELECT root_id, account_id, customer_id, array_agg(payment_id ORDER BY payment_id) AS payment_ids,
          SUM(payment_amount) AS signed_net, SUM(ABS(payment_amount)) AS magnitude,
          COUNT(*) FILTER (WHERE payment_amount > 0) AS positive_events
   FROM resolved GROUP BY root_id, account_id, customer_id
), u AS (
   UPDATE customer_invoices i
   SET total_payments = s.signed_net
   FROM sums s
   JOIN _m019_reviewed m
      ON m.root_id = s.root_id
     AND m.account_id = s.account_id
     AND m.customer_id = s.customer_id
     AND m.expected_payment_ids = s.payment_ids
     AND m.expected_signed_net = s.signed_net
   WHERE i.customer_invoice_id = s.root_id
     AND i.parent_invoice_id IS NULL
     AND i.account_id = s.account_id AND i.customer_id = s.customer_id
     AND i.total_payments = m.expected_old_total
     AND i.total_payments > 0
     AND i.total_payments = s.magnitude
     -- N6: no reversal/positive event anywhere in this root's OWN (account/customer-scoped)
     -- resolved-payment group — a hand-edited manifest row can't sneak a positive-only chain
     -- through even if every other predicate above happens to match.
     AND s.positive_events = 0
     -- N4: quarantine any chain with conflicting ownership — a payment, or a payment reachable
     -- through a linked child invoice, whose account_id/customer_id differs from this root's.
     -- Arithmetic equality on the root's OWN group (checked above) is not enough: a foreign
     -- payment can sit elsewhere in the same chain via a child invoice while the root's own
     -- group still matches exactly (see the header comment, finding N4).
     -- R2 fix (2026-09 second follow-up review): start from the LINKED INVOICES and LEFT JOIN
     -- their payments, not the other way around. Starting from customer_payments (an inner join)
     -- made a foreign-owned child invoice with NO payment of its own invisible to this check —
     -- there was no "bad" payment row to find, so it flipped anyway. A same-owner child with no
     -- payment must stay eligible: bad.payment_id IS NULL means "no payment to compare", never
     -- itself a conflict.
     AND NOT EXISTS (
            SELECT 1 FROM customer_invoices linked
            LEFT JOIN customer_payments bad ON bad.customer_invoice_id = linked.customer_invoice_id
            WHERE COALESCE(linked.parent_invoice_id, linked.customer_invoice_id) = i.customer_invoice_id
              AND ((bad.payment_id IS NOT NULL
                    AND (bad.account_id, bad.customer_id) IS DISTINCT FROM (i.account_id, i.customer_id))
                OR (linked.account_id, linked.customer_id) IS DISTINCT FROM (i.account_id, i.customer_id))
         )
   RETURNING i.customer_invoice_id, i.account_id, i.customer_id, s.magnitude AS old_value, i.total_payments AS new_value
), logged AS (
   INSERT INTO ledger_normalization_log (migration, table_name, row_id, account_id, customer_id, column_name, old_value, new_value)
   SELECT '019', 'customer_invoices', customer_invoice_id, account_id, customer_id, 'total_payments', old_value::text, new_value::text FROM u
   RETURNING 1
)
INSERT INTO _m019_counts SELECT 'invoices.total_payments positive->signed net (reviewed manifest rows only; see ledger_normalization_log)', count(*) FROM logged;

