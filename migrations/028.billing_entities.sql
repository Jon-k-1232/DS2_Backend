CREATE OR REPLACE FUNCTION ds2_effective_entity(aid integer,t text,rid integer,eid integer) RETURNS integer LANGUAGE sql STABLE SET search_path=public,pg_temp AS $$
 SELECT COALESCE(eid,
 (SELECT a.billing_entity_id FROM legacy_financial_entity_attributions a WHERE a.account_id=aid AND a.table_name=t AND a.record_id=rid),
 (SELECT s.billing_entity_id FROM billing_entity_reviews r JOIN billing_entity_resolutions s USING(review_id,account_id) WHERE r.account_id=aid AND r.table_name=t AND r.record_id=rid))
$$;
-- Read-only entity projection. The application opts in transaction-locally; writes use public.
CREATE SCHEMA IF NOT EXISTS billing_scope;
DO $$ DECLARE spec text; t text; k text; cols text; expr text; BEGIN
 FOREACH spec IN ARRAY ARRAY[
 'customer_transactions:transaction_id','customer_payments:payment_id','customer_writeoffs:writeoff_id','customer_retainers_and_prepayments:retainer_id',
 'customer_invoices:customer_invoice_id','retainer_events:event_id','invoice_issues:invoice_id','recurring_customers:recurring_customer_id',
 'customer_quotes:customer_quote_id','customer_jobs:customer_job_id','customer_payments_processed:payment_id',
 'timesheet_entries:timesheet_entry_id','ai_time_tracker_transaction_suggestions:suggestion_id'] LOOP
 t:=split_part(spec,':',1); k:=split_part(spec,':',2);
 SELECT string_agg('r.'||quote_ident(column_name),', ' ORDER BY ordinal_position) INTO cols FROM information_schema.columns
 WHERE table_schema='public' AND table_name=t AND column_name<>'billing_entity_id';
 expr:=format('public.ds2_effective_entity(r.account_id,%L,r.%I,r.billing_entity_id)',t,k);
 EXECUTE format('CREATE OR REPLACE VIEW billing_scope.%I AS SELECT %s,%s AS billing_entity_id FROM public.%I r WHERE NULLIF(current_setting(''app.billing_entity_id'',true),'''') IS NULL OR %s=NULLIF(current_setting(''app.billing_entity_id'',true),'''')::integer %s',t,cols,expr,t,expr,CASE WHEN t='customer_jobs' THEN 'OR r.billing_entity_id IS NULL' ELSE '' END);
 END LOOP;
END $$;
