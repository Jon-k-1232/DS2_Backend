CREATE OR REPLACE FUNCTION ds2_normalize_entity(s text) RETURNS text LANGUAGE sql IMMUTABLE AS $$
 SELECT btrim(regexp_replace(regexp_replace(lower(normalize(COALESCE(s,''),NFKC)),'[[:punct:]]','','g'),'[[:space:]]+',' ','g'))
$$;
CREATE TABLE IF NOT EXISTS billing_entities (
 billing_entity_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 account_id integer NOT NULL REFERENCES accounts(account_id),
 name text NOT NULL CHECK(length(btrim(name)) BETWEEN 1 AND 150),
 legal_name text NOT NULL CHECK(length(btrim(legal_name)) BETWEEN 1 AND 200),
 contact_name text, email text, phone text, address_line1 text, address_line2 text,
 city text, state text, postal_code text, country text NOT NULL DEFAULT 'US',
 logo_key text, logo_sha256 text CHECK(logo_sha256 IS NULL OR logo_sha256 ~ '^[a-f0-9]{64}$'),
 invoice_prefix text NOT NULL CHECK(invoice_prefix ~ '^[A-Z]{1,12}$'),
 active boolean NOT NULL DEFAULT true, is_default boolean NOT NULL DEFAULT false,
 version integer NOT NULL DEFAULT 1 CHECK(version>0),
 created_at timestamptz NOT NULL DEFAULT clock_timestamp(), updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 CHECK(NOT is_default OR active), UNIQUE(account_id,billing_entity_id), UNIQUE(account_id,invoice_prefix)
);
CREATE UNIQUE INDEX IF NOT EXISTS billing_entity_name_unique ON billing_entities(account_id,ds2_normalize_entity(name));
CREATE UNIQUE INDEX IF NOT EXISTS billing_entity_default_unique ON billing_entities(account_id) WHERE is_default;
CREATE TABLE IF NOT EXISTS billing_entity_aliases (
 alias_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 account_id integer NOT NULL, billing_entity_id integer NOT NULL,
 alias text NOT NULL CHECK(length(btrim(alias)) BETWEEN 1 AND 200),
 normalized_alias text GENERATED ALWAYS AS (ds2_normalize_entity(alias)) STORED,
 source text NOT NULL, reason text NOT NULL CHECK(length(btrim(reason)) BETWEEN 1 AND 2000),
 created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 FOREIGN KEY(account_id,billing_entity_id) REFERENCES billing_entities(account_id,billing_entity_id),
 UNIQUE(account_id,billing_entity_id,normalized_alias)
);
CREATE TABLE IF NOT EXISTS billing_entity_invoice_sequences (
 account_id integer NOT NULL, billing_entity_id integer NOT NULL, year integer NOT NULL CHECK(year BETWEEN 1900 AND 9999),
 last_number integer NOT NULL DEFAULT 0 CHECK(last_number BETWEEN 0 AND 99999),
 PRIMARY KEY(account_id,billing_entity_id,year), FOREIGN KEY(account_id,billing_entity_id) REFERENCES billing_entities(account_id,billing_entity_id)
);
CREATE TABLE IF NOT EXISTS billing_cutovers (
 cutover_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 account_id integer NOT NULL REFERENCES accounts(account_id),
 source text NOT NULL, manifest jsonb NOT NULL, manifest_sha256 text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT clock_timestamp(), UNIQUE(account_id,source), UNIQUE(account_id,cutover_id)
);
CREATE TABLE IF NOT EXISTS legacy_financial_entity_attributions (
 attribution_id bigserial PRIMARY KEY, account_id integer NOT NULL, customer_id integer,
 table_name text NOT NULL, record_id integer NOT NULL, billing_entity_id integer NOT NULL,
 cutover_id integer NOT NULL, basis text NOT NULL, source_sha256 text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 UNIQUE(account_id,table_name,record_id),
 FOREIGN KEY(account_id,billing_entity_id) REFERENCES billing_entities(account_id,billing_entity_id),
 FOREIGN KEY(account_id,cutover_id) REFERENCES billing_cutovers(account_id,cutover_id)
);
CREATE TABLE IF NOT EXISTS billing_entity_reviews (
 review_id bigserial PRIMARY KEY, account_id integer NOT NULL REFERENCES accounts(account_id), customer_id integer,
 table_name text NOT NULL CHECK(table_name IN ('timesheet_entries','customer_transactions')),
 record_id integer NOT NULL, raw_entity text, candidate_ids integer[] NOT NULL DEFAULT '{}',
 source_sha256 text NOT NULL, reason_code text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT clock_timestamp(), UNIQUE(account_id,table_name,record_id)
);
CREATE TABLE IF NOT EXISTS billing_entity_resolutions (
 resolution_id bigserial PRIMARY KEY, account_id integer NOT NULL, customer_id integer,
 review_id bigint NOT NULL UNIQUE REFERENCES billing_entity_reviews(review_id),
 billing_entity_id integer NOT NULL, reason text NOT NULL CHECK(length(btrim(reason)) BETWEEN 1 AND 2000),
 source_sha256 text NOT NULL, created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 FOREIGN KEY(account_id,billing_entity_id) REFERENCES billing_entities(account_id,billing_entity_id)
);
CREATE OR REPLACE FUNCTION ds2_entity_match(aid integer, raw_name text) RETURNS integer[] LANGUAGE sql STABLE SET search_path=public,pg_temp AS $$
 SELECT COALESCE(array_agg(DISTINCT e.billing_entity_id ORDER BY e.billing_entity_id),'{}'::integer[])
 FROM billing_entities e LEFT JOIN billing_entity_aliases a USING(account_id,billing_entity_id)
 WHERE e.account_id=aid AND e.active AND ds2_normalize_entity(raw_name)<>''
 AND ds2_normalize_entity(raw_name) IN(ds2_normalize_entity(e.name),ds2_normalize_entity(e.legal_name),a.normalized_alias)
$$;
